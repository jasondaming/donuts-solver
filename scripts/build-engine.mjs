// Compiles engine/wdl.c to WebAssembly and embeds it in src/solver/wdlWasm.ts (base64), so the browser
// worker, the Node service, and scripts all load the same engine without bundler or loader support.
// Needs clang with the wasm32 target and wasm-ld (any LLVM release). Set CLANG to override the path.
//   npm run build:engine
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const windowsClang = 'C:/Program Files/LLVM/bin/clang.exe';
const clang = process.env.CLANG ?? (existsSync(windowsClang) ? windowsClang : 'clang');
const out = mkdtempSync(path.join(tmpdir(), 'donuts-wdl-'));
const wasmPath = path.join(out, 'wdl.wasm');

try {
  execFileSync(clang, [
    '--target=wasm32', '-O3', '-nostdlib', '-mbulk-memory',
    '-Wall', '-Wextra', '-Wno-unused-parameter',
    '-Wl,--no-entry', '-Wl,--strip-all', '-Wl,-z,stack-size=1048576',
    '-o', wasmPath, path.join(root, 'engine/wdl.c'),
  ], { stdio: 'inherit' });

  const wasm = readFileSync(wasmPath);
  const source = [
    '// Generated by scripts/build-engine.mjs from engine/wdl.c. Do not edit.',
    `export const WDL_WASM_BASE64 = '${wasm.toString('base64')}';`,
    '',
  ].join('\n');
  writeFileSync(path.join(root, 'src/solver/wdlWasm.ts'), source);
  console.log(`engine: ${wasm.length} bytes -> src/solver/wdlWasm.ts`);
} finally {
  rmSync(out, { recursive: true, force: true });
}
